#!/usr/bin/env bash
# goax installer
# Usage:
#   curl -fsSL https://raw.githubusercontent.com/bluecheat/ax/main/install.sh | bash
#   curl -fsSL https://raw.githubusercontent.com/bluecheat/ax/main/install.sh | bash -s -- --mode submodule
set -euo pipefail

REPO_URL="${GOAX_REPO:-git@github.com:bluecheat/ax.git}"
INSTALL_DIR="${GOAX_HOME:-$HOME/.goax}"
BIN_DIR="${GOAX_BIN:-$HOME/.local/bin}"
MODE="standalone"   # standalone | submodule
BRANCH="${GOAX_BRANCH:-main}"

# ───────────────────────────────────────────────────────────
# arg parse
# ───────────────────────────────────────────────────────────
while [ $# -gt 0 ]; do
    case "$1" in
        --mode) MODE="$2"; shift 2 ;;
        --branch) BRANCH="$2"; shift 2 ;;
        --repo) REPO_URL="$2"; shift 2 ;;
        --help|-h)
            cat <<'EOF'
goax installer

  --mode standalone     ~/.goax/ 에 클론 + ~/.local/bin/goax symlink (default)
  --mode submodule      현재 프로젝트에 git submodule add .goax-tool
  --branch <name>       특정 브랜치 사용 (default: main)
  --repo <url>          다른 repo URL (default: git@github.com:bluecheat/ax.git)
EOF
            exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 1 ;;
    esac
done

# ───────────────────────────────────────────────────────────
# pre-flight
# ───────────────────────────────────────────────────────────
say() { printf "\033[36m[goax]\033[0m %s\n" "$*"; }
warn() { printf "\033[33m[goax]\033[0m %s\n" "$*" >&2; }
die() { printf "\033[31m[goax]\033[0m %s\n" "$*" >&2; exit 1; }

command -v git >/dev/null 2>&1 || die "git이 필요해. brew install git"
command -v bash >/dev/null 2>&1 || die "bash 4+ 필요"

# ───────────────────────────────────────────────────────────
# install
# ───────────────────────────────────────────────────────────
case "$MODE" in
  standalone)
    if [ -d "$INSTALL_DIR/.git" ]; then
      say "이미 설치됨 — 업데이트 시도"
      git -C "$INSTALL_DIR" fetch --quiet origin "$BRANCH"
      git -C "$INSTALL_DIR" reset --hard "origin/$BRANCH"
    else
      say "$REPO_URL → $INSTALL_DIR"
      git clone --quiet --branch "$BRANCH" "$REPO_URL" "$INSTALL_DIR"
    fi

    mkdir -p "$BIN_DIR"
    ln -sf "$INSTALL_DIR/bin/goax" "$BIN_DIR/goax"

    say "설치 완료."
    say "  binary: $BIN_DIR/goax"
    say "  source: $INSTALL_DIR"

    if ! echo ":$PATH:" | grep -q ":$BIN_DIR:"; then
      warn "PATH에 $BIN_DIR 추가가 필요해. 다음 한 줄을 ~/.zshrc 또는 ~/.bashrc에 넣어:"
      printf '    export PATH="%s:$PATH"\n' "$BIN_DIR"
    fi
    ;;

  submodule)
    [ -d ".git" ] || die "현재 디렉토리가 git repo가 아님 — submodule 모드는 프로젝트 루트에서 실행"
    if [ -d ".goax-tool" ]; then
      say "이미 submodule 존재 — 업데이트"
      git submodule update --remote --merge .goax-tool
    else
      say "submodule add $REPO_URL → .goax-tool"
      git submodule add -b "$BRANCH" "$REPO_URL" .goax-tool
      git submodule update --init --recursive
    fi

    mkdir -p .goax
    cat > .goax/.bin <<'EOF'
#!/usr/bin/env bash
# Auto-generated by goax installer (submodule mode)
exec "$(git rev-parse --show-toplevel)/.goax-tool/bin/goax" "$@"
EOF
    chmod +x .goax/.bin

    say "submodule 설치 완료."
    say "  사용: ./.goax/.bin <command>  (또는 alias 'goax=./.goax/.bin')"
    ;;

  *) die "알 수 없는 모드: $MODE (standalone | submodule)" ;;
esac

say "다음 단계: goax up [--preset ax]"
